/**
 * TurtleFont — the glyph data.
 *
 * Separated from the behaviour in `turtlefont.js` for the same reason the
 * shape table is separate from the collision engine: this file is a drawing,
 * and it should be readable as one.
 *
 * THE GRID. Every coordinate is a whole quadrant. x runs right from the glyph
 * origin; y runs UP from the baseline, which is the one place in this engine
 * where y is not screen-down — because that is how every type designer, and
 * every stroke font since Hershey, has described a letter, and translating at
 * the point of use is cheaper than reading upside down for the whole file.
 *
 *      y = 8   ─── accent ceiling
 *      y = 6   ─── cap height / ascender
 *      y = 4   ─── x-height
 *      y = 0   ─── baseline
 *      y = -2  ─── descender
 *
 * THE FORMAT. `[width, ...strokes]`, where a stroke is a polyline written as
 * space-separated `x,y` points. A one-point stroke is a dot — the tittle on an
 * `i`, a full stop. `width` is the drawing width; the advance is width + 2, so
 * spacing is a property of the metrics rather than something re-decided per
 * glyph.
 *
 * POLYLINES ONLY, no curves. At six quadrants of cap height the lattice
 * quantises a sampled curve to almost exactly the polyline anyway, and a
 * sampling parameter would be one more thing that could make measurement and
 * rendering disagree. Round letters are drawn as cut corners on purpose.
 *
 * COMPOSED GLYPHS are `{ base, mark }` — an accented letter is its letter plus
 * a mark centred over it, so `Ä` cannot drift away from `A`, and adding a new
 * accented form costs one line rather than one drawing.
 */

